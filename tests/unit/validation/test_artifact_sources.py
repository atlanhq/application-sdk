def test_single_entrypoint_looks_only_at_the_flat_file(tmp_path: Path) -> None:
    assert artifact_schema_paths(generated_dir=tmp_path) == (
        tmp_path / ARTIFACT_SCHEMAS_FILENAME,
    )


def test_multi_entrypoint_prefers_its_own_file(tmp_path: Path) -> None:
    assert artifact_schema_paths(entrypoint="extract", generated_dir=tmp_path) == (
        tmp_path / "extract" / ARTIFACT_SCHEMAS_FILENAME,
        tmp_path / ARTIFACT_SCHEMAS_FILENAME,
    )


def test_entrypoint_file_wins_over_the_flat_one(tmp_path: Path) -> None:
    _load_schemas.cache_clear()
    _write(
        tmp_path / ARTIFACT_SCHEMAS_FILENAME,
        _valid_document(
            schemas={
                "edges": {
                    "format": FORMAT_NDJSON,
                    "fields": [{"name": "flat", "type": "string"}],
                }
            }
        ),
    )
    _write(
        tmp_path / "extract" / ARTIFACT_SCHEMAS_FILENAME,
        _valid_document(
            schemas={
                "edges": {
                    "format": FORMAT_NDJSON,
                    "fields": [{"name": "per_entrypoint", "type": "string"}],
                }
            }
        ),
    )
    declaration = ContractSource(
        field="edges", entrypoint="extract", generated_dir=tmp_path
    ).resolve()
    assert declaration is not None
    assert [f.path for f in declaration.fields] == ["per_entrypoint"]


def test_an_entrypoints_own_file_is_the_final_answer(tmp_path: Path) -> None:
    """A field its own file omits is ``not_declared`` — never the flat file's answer.

    Falling through would answer one entrypoint's question with another scope's
    declarations. The toolkit removes the bundle-root half of that hazard by
    refusing to generate a root file; this is the loader's half.
    """
    _load_schemas.cache_clear()
    _write(tmp_path / ARTIFACT_SCHEMAS_FILENAME, _valid_document())
    _write(
        tmp_path / "extract" / ARTIFACT_SCHEMAS_FILENAME,
        _valid_document(
            schemas={
                "other": {
                    "format": FORMAT_NDJSON,
                    "fields": [{"name": "a", "type": "string"}],
                }
            }
        ),
    )
    assert (
        ContractSource(
            field="edges", entrypoint="extract", generated_dir=tmp_path
        ).resolve()
        is None
    )


def test_flat_file_is_used_when_the_entrypoint_has_no_file(tmp_path: Path) -> None:
    """A single-entrypoint app still knows its entrypoint name; the fallback is safe."""
    _load_schemas.cache_clear()
    _write(tmp_path / ARTIFACT_SCHEMAS_FILENAME, _valid_document())
    declaration = ContractSource(
        field="edges", entrypoint="extract", generated_dir=tmp_path
    ).resolve()
    assert isinstance(declaration, FieldMapDeclaration)


