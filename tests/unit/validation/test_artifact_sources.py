def test_fixture_is_the_generated_example() -> None:
    """The committed fixture is byte-identical to the toolkit's own example.

    Copied rather than read in place so the validation suite stays self-contained,
    and guarded rather than trusted so the copy cannot drift: the loader's contract
    *is* the toolkit's output shape, and a change to one that does not reach the
    other is precisely the producer/consumer disagreement this capability exists to
    catch — here, between the toolkit and the SDK themselves.
    """
    assert TOOLKIT_EXAMPLE.exists(), f"toolkit example missing at {TOOLKIT_EXAMPLE}"
    assert FIXTURE.read_bytes() == TOOLKIT_EXAMPLE.read_bytes(), (
        f"{FIXTURE} has drifted from {TOOLKIT_EXAMPLE}. Re-copy it: the SDK loader "
        f"must keep reading exactly what the contract toolkit generates."
    )


