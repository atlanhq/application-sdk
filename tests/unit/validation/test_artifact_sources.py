def test_source_satisfies_the_protocol() -> None:
    assert isinstance(ContractSource(field="raw_queries"), SchemaSource)
    assert isinstance(ModelSource(model=DeclaredField), SchemaSource)


def test_kinds_are_the_pinned_telemetry_values() -> None:
    """These land on the outcome event; rewording them breaks queries in place."""
    assert ContractSource(field="x").kind == "contract"
    assert ModelSource(model=DeclaredField).kind == "model"


def test_loads_a_parquet_declaration(generated_dir: Path) -> None:
    declaration = ContractSource(
        field="raw_queries", generated_dir=generated_dir
    ).resolve()

    assert isinstance(declaration, FieldMapDeclaration)
    assert declaration.artifact_format == FORMAT_PARQUET
    assert declaration.field_count == 6
    assert [f.path for f in declaration.fields] == [
        "QUERY_ID",
        "START_TIME",
        "CREDITS_USED",
        "ROWS_PRODUCED",
        "YEAR",
        "SESSION_PARAMS",
    ]


def test_the_load_bearing_type_survives_the_round_trip(generated_dir: Path) -> None:
    """``START_TIME`` is a ``timestamp``, not a string.

    The single asymmetry the whole capability exists to assert — a 73-day frozen
    lineage marker traced to that one column having become a string. If the loader
    ever flattened the vocabulary, this is the assertion that would notice.
    """
    declaration = ContractSource(
        field="raw_queries", generated_dir=generated_dir
    ).resolve()
    assert declaration is not None
    assert _field(declaration, "START_TIME").type == "timestamp"
    assert _field(declaration, "QUERY_ID").type == "string"


def test_optional_and_extended_types_survive(generated_dir: Path) -> None:
    declaration = ContractSource(
        field="raw_queries", generated_dir=generated_dir
    ).resolve()
    assert declaration is not None

    credits = _field(declaration, "CREDITS_USED")
    assert credits.required is False
    assert credits.type == "float"

    # `decimal` is an extension member: a Snowflake NUMBER lands as parquet
    # decimal128, and asserting float would mis-flag it or lose precision.
    assert _field(declaration, "ROWS_PRODUCED").type == "decimal"
    # `json` is physically a string column and semantically not — collapsing the
    # two would defeat this hop's check.
    assert _field(declaration, "SESSION_PARAMS").type == "json"


def test_nested_paths_load_verbatim(generated_dir: Path) -> None:
    """Dotted paths and ``[]`` element steps are carried through unchanged.

    Nested payloads are declared as a *flat set of paths plus container types*, not
    a recursive grammar. A loader that parsed the paths into a tree would have to
    re-serialise them for the validator, and ``[]`` — which says "descend into the
    list" in logical terms rather than parquet's encoding-dependent
    ``columns.list.element`` — is exactly what such a round trip loses.
    """
    declaration = ContractSource(
        field="transformed_entities", generated_dir=generated_dir
    ).resolve()
    assert declaration is not None
    assert declaration.artifact_format == FORMAT_NDJSON

    paths = [f.path for f in declaration.fields]
    assert "attributes" in paths
    assert "attributes.qualifiedName" in paths
    assert "attributes.columns" in paths
    assert "attributes.columns[]" in paths
    assert "attributes.columns[].name" in paths

    assert _field(declaration, "attributes").type == "struct"
    assert _field(declaration, "attributes.columns").type == "array"
    assert _field(declaration, "attributes.columns[]").type == "struct"
    assert _field(declaration, "attributes.columns[].order").type == "int"
    assert _field(declaration, "attributes.tags[]").type == "string"
    # `any` is "must be present, type not asserted" — declared rather than someone
    # inventing a wrong type to satisfy the vocabulary.
    assert _field(declaration, "customAttributes").type == "any"


def test_descriptions_are_carried_through(generated_dir: Path) -> None:
    """The toolkit requires a description per field; the loader must not drop it.

    It is the only place a ``type = "any"`` field can say what it is, and it is read
    by whoever is debugging the hand-off that just failed.
    """
    declaration = ContractSource(
        field="raw_queries", generated_dir=generated_dir
    ).resolve()
    assert declaration is not None
    assert all(f.description for f in declaration.fields)
    assert "join key" in _field(declaration, "QUERY_ID").description


def test_an_input_artifact_is_declarable(generated_dir: Path) -> None:
    """The consumer declares what it requires of what it *reads*, not just writes."""
    declaration = ContractSource(
        field="upstream_lineage", generated_dir=generated_dir
    ).resolve()
    assert isinstance(declaration, FieldMapDeclaration)
    assert declaration.field_count == 3


def test_declarations_are_frozen(generated_dir: Path) -> None:
    """Nothing hands out a mutable declaration — the parse is cached and shared."""
    declaration = ContractSource(
        field="raw_queries", generated_dir=generated_dir
    ).resolve()
    assert declaration is not None
    with pytest.raises(dataclasses.FrozenInstanceError):
        # Deliberate: assigning to a frozen field is the thing under test, so the
        # checker's complaint is the behaviour being asserted at runtime.
        declaration.fields[0].type = "string"  # type: ignore[misc]


