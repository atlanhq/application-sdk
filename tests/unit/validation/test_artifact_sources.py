class _Model:
    """Stands in for a pyatlan_v9 asset: all that is asked is a callable ``validate``."""

    def validate(self) -> list[str]:
        return []


def test_model_source_resolves_to_delegation() -> None:
    declaration = ModelSource(model=_Model).resolve()
    assert isinstance(declaration, ModelDeclaration)
    assert declaration.model is _Model
    assert declaration.artifact_format == FORMAT_NDJSON
    # A model declares no enumerable field list at this layer — the count is 0, and
    # a validator that diffed against it would be diffing against nothing.
    assert declaration.field_count == 0


def test_model_source_never_returns_none() -> None:
    """The model *is* the declaration, so a ModelSource always has one."""
    assert ModelSource(model=_Model).resolve() is not None


def test_model_source_carries_the_parquet_cell() -> None:
    """parquet x model resolves and is refused at dispatch, not here.

    The cell has to be *reachable* for the wrapper to report ``unsupported`` on it.
    Refusing it at construction would turn a stated gap back into silence.
    """
    declaration = ModelSource(model=_Model, artifact_format=FORMAT_PARQUET).resolve()
    assert declaration.artifact_format == FORMAT_PARQUET


def test_model_without_validate_is_an_error() -> None:
    class _NoValidate:
        pass

    with pytest.raises(ArtifactDeclarationError, match="no 'validate' method"):
        ModelSource(model=_NoValidate).resolve()


def test_non_callable_validate_is_an_error() -> None:
    class _NotCallable:
        validate = "nope"

    with pytest.raises(ArtifactDeclarationError, match="not callable"):
        ModelSource(model=_NotCallable).resolve()


def test_an_instance_is_not_a_model() -> None:
    """An easy mistake — passing the asset rather than its class."""
    with pytest.raises(ArtifactDeclarationError, match="must be a class"):
        # Deliberate: passing an instance where a class is required is the mistake
        # under test — the checker catching it is the point, not an obstacle.
        ModelSource(model=_Model()).resolve()  # type: ignore[arg-type]
