"""Tests for the two schema sources (ADR-0020, FND-686).

The fixture is a **byte copy of real contract-toolkit output** —
``contract-toolkit/examples/artifact-schemas/app/generated/artifact_schemas.json``,
generated by the toolkit's own example. A hand-built declaration object would test
the dataclasses and skip the loader; a hand-written JSON blob would test the loader
against a shape nobody generates. :func:`test_fixture_is_the_generated_example`
holds the copy honest, so a change to what the toolkit emits fails here rather than
in production.

Three properties are worth defending, because each has a quiet failure mode:

* **The loader reads what the toolkit writes** — every field, its logical type, its
  ``required`` flag and its ``description``, including the nested dotted and ``[]``
  paths, which is the shape a recursive-grammar rewrite would silently drop.
* **Two answers, not one.** "No declaration" (``None``) and "unreadable
  declaration" (``ArtifactDeclarationError``) stay apart. Collapsed, a loader
  failure would be reported as ``not_declared`` — a finding against an app for a
  file it wrote correctly.
* **Nothing dict-shaped on the seam.** A source hands back typed declarations, and
  the entrypoint-level query hands back a tuple of names.
"""

from __future__ import annotations

import dataclasses
from pathlib import Path

import orjson
import pytest

from application_sdk.validation.artifacts import (
    FORMAT_NDJSON,
    FORMAT_PARQUET,
    DeclaredField,
    FieldMapDeclaration,
    ModelDeclaration,
)
from application_sdk.validation.protocols import SchemaSource
from application_sdk.validation.sources import (
    ARTIFACT_SCHEMAS_ENVELOPE_VERSION,
    ARTIFACT_SCHEMAS_FILENAME,
    ArtifactDeclarationError,
    ContractSource,
    ModelSource,
    _load_schemas,
    artifact_schema_paths,
    declared_artifact_fields,
)

RESOURCES = Path(__file__).parent / "resources"
FIXTURE = RESOURCES / ARTIFACT_SCHEMAS_FILENAME

TOOLKIT_EXAMPLE = (
    Path(__file__).parents[3]
    / "contract-toolkit"
    / "examples"
    / "artifact-schemas"
    / "app"
    / "generated"
    / ARTIFACT_SCHEMAS_FILENAME
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


@pytest.fixture
def generated_dir(tmp_path: Path) -> Path:
    """A generated-contract directory holding the real toolkit output, flat.

    ``_load_schemas`` is cached per path and ``tmp_path`` is unique per test, so no
    cache clearing is needed — but the cache is cleared anyway so a test that writes
    to a fixed path cannot inherit another test's parse.
    """
    _load_schemas.cache_clear()
    (tmp_path / ARTIFACT_SCHEMAS_FILENAME).write_bytes(FIXTURE.read_bytes())
    return tmp_path


def _write(path: Path, document: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(orjson.dumps(document))


def _valid_document(**overrides: object) -> dict:
    """The smallest document the loader accepts, before ``overrides`` are applied."""
    document = {
        "version": ARTIFACT_SCHEMAS_ENVELOPE_VERSION,
        "schemas": {
            "edges": {
                "format": FORMAT_NDJSON,
                "fields": [
                    {
                        "name": "process_id",
                        "type": "string",
                        "required": True,
                        "description": "Groups edges into one lineage process.",
                    }
                ],
            }
        },
    }
    document.update(overrides)
    return document


def _field(declaration: FieldMapDeclaration, path: str) -> DeclaredField:
    match = [f for f in declaration.fields if f.path == path]
    assert match, f"{path} not declared; got {[f.path for f in declaration.fields]}"
    return match[0]


