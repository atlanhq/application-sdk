@pytest.mark.parametrize(
    ("case", "document"),
    [
        ("newer envelope", _valid_document(version=2)),
        ("no envelope", _valid_document(version=None)),
        ("top level is a list", []),
        ("schemas is not an object", _valid_document(schemas=[])),
        (
            "schema entry is not an object",
            _valid_document(schemas={"edges": "ndjson"}),
        ),
        (
            "no format declared",
            _valid_document(schemas={"edges": {"fields": [{"name": "a"}]}}),
        ),
        (
            "no fields list",
            _valid_document(schemas={"edges": {"format": FORMAT_NDJSON}}),
        ),
        (
            "zero fields",
            _valid_document(schemas={"edges": {"format": FORMAT_NDJSON, "fields": []}}),
        ),
        (
            "field is not an object",
            _valid_document(
                schemas={"edges": {"format": FORMAT_NDJSON, "fields": ["a"]}}
            ),
        ),
        (
            "field has no name",
            _valid_document(
                schemas={
                    "edges": {"format": FORMAT_NDJSON, "fields": [{"type": "string"}]}
                }
            ),
        ),
        (
            "required is not a boolean",
            _valid_document(
                schemas={
                    "edges": {
                        "format": FORMAT_NDJSON,
                        "fields": [{"name": "a", "required": "yes"}],
                    }
                }
            ),
        ),
    ],
)
def test_malformed_declaration_raises_rather_than_returning_none(
    tmp_path: Path, case: str, document: object
) -> None:
    """Every malformed shape is an error, and specifically *not* ``None``.

    ``None`` means ``not_declared``, which on a public boundary is a finding against
    the app. A file the app wrote and the SDK could not read must never be reported
    that way — the wrapper turns this raise into ``absent`` plus a warning instead.
    """
    _load_schemas.cache_clear()
    _write(tmp_path / ARTIFACT_SCHEMAS_FILENAME, document)
    with pytest.raises(ArtifactDeclarationError):
        ContractSource(field="edges", generated_dir=tmp_path).resolve()


def test_zero_field_schema_is_refused_by_name(tmp_path: Path) -> None:
    """A hand-edited zero-field schema cannot reintroduce "adopted but checks nothing"."""
    _load_schemas.cache_clear()
    _write(
        tmp_path / ARTIFACT_SCHEMAS_FILENAME,
        _valid_document(schemas={"edges": {"format": FORMAT_NDJSON, "fields": []}}),
    )
    with pytest.raises(ArtifactDeclarationError, match="zero fields"):
        ContractSource(field="edges", generated_dir=tmp_path).resolve()


def test_unparseable_json_raises(tmp_path: Path) -> None:
    _load_schemas.cache_clear()
    (tmp_path / ARTIFACT_SCHEMAS_FILENAME).write_text("{not json")
    with pytest.raises(ArtifactDeclarationError, match="not valid JSON"):
        ContractSource(field="edges", generated_dir=tmp_path).resolve()


def test_empty_file_raises(tmp_path: Path) -> None:
    """Empty is malformed, not absent: the toolkit never writes a zero-byte file."""
    _load_schemas.cache_clear()
    (tmp_path / ARTIFACT_SCHEMAS_FILENAME).write_bytes(b"")
    with pytest.raises(ArtifactDeclarationError):
        ContractSource(field="edges", generated_dir=tmp_path).resolve()


def test_unknown_logical_type_is_not_policed(tmp_path: Path) -> None:
    """A newer toolkit's type loads; the *validator* resolves it to unsupported.

    Rejecting the whole file would drop every other assertion in it because one
    field used a member this SDK has not learned yet.
    """
    _load_schemas.cache_clear()
    _write(
        tmp_path / ARTIFACT_SCHEMAS_FILENAME,
        _valid_document(
            schemas={
                "edges": {
                    "format": FORMAT_NDJSON,
                    "fields": [{"name": "a", "type": "geography"}],
                }
            }
        ),
    )
    declaration = ContractSource(field="edges", generated_dir=tmp_path).resolve()
    assert declaration is not None
    assert _field(declaration, "a").type == "geography"


def test_unknown_format_is_not_policed(tmp_path: Path) -> None:
    """Same reasoning one level up: dispatch reports ``unsupported``, not ``absent``."""
    _load_schemas.cache_clear()
    _write(
        tmp_path / ARTIFACT_SCHEMAS_FILENAME,
        _valid_document(
            schemas={"edges": {"format": "avro", "fields": [{"name": "a"}]}}
        ),
    )
    declaration = ContractSource(field="edges", generated_dir=tmp_path).resolve()
    assert declaration is not None
    assert declaration.artifact_format == "avro"


